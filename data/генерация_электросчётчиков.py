# -*- coding: utf-8 -*-
"""
Генерация файла engineer_meters.json для личного кабинета
собственника из Excel-файла «Октябрь Мосэнерго.xlsx».
"""

import json
import os
import re
import openpyxl

# ─────────────────────────────────────────────────────────────────
# УМНЫЕ ПУТИ (всегда берут папку, где лежит сам скрипт)
# ─────────────────────────────────────────────────────────────────
ПАПКА_СКРИПТА = os.path.dirname(os.path.abspath(__file__))

# Файлы ищутся и сохраняются ровно там же, где лежит этот скрипт
ИСХОДНЫЙ_ФАЙЛ = os.path.join(ПАПКА_СКРИПТА, "Октябрь Мосэнерго.xlsx")
ВЫХОДНОЙ_ФАЙЛ = os.path.join(ПАПКА_СКРИПТА, "engineer_meters.json")

ЛИСТ = 0
ДАТА_ПОКАЗАНИЙ = "2026-10-01"
УЧАСТОК_РЕГЕКС = re.compile(r'^([0-9]+(?:/[0-9]+)*(?:\([^)]*\))?|Э[0-9]+)$')


def извлечь_участок(значение):
    if not значение:
        return None
    строка = str(значение).strip()
    строка = " ".join(строка.split())
    if УЧАСТОК_РЕГЕКС.match(строка):
        return строка
    return None


def прочитать_excel(путь):
    wb = openpyxl.load_workbook(путь, data_only=True)
    ws = wb.worksheets[ЛИСТ]
    записи = []

    текущий_участок = None
    текущие_показания = {}

    for строка in ws.iter_rows(min_row=1, values_only=True):
        if not строка or len(строка) < 11:
            continue

        участок_ячейка = строка[0]
        участок = извлечь_участок(участок_ячейка)
        
        if участок:
            if текущий_участок and текущие_показания:
                записи.append({
                    "lot": текущий_участок,
                    "date": ДАТА_ПОКАЗАНИЙ,
                    "t1_cur": текущие_показания.get("Т1", {}).get("стало"),
                    "t1_prev": текущие_показания.get("Т1", {}).get("было"),
                    "t2_cur": текущие_показания.get("Т2", {}).get("стало"),
                    "t2_prev": текущие_показания.get("Т2", {}).get("было"),
                    "t3_cur": текущие_показания.get("Т3", {}).get("стало"),
                    "t3_prev": текущие_показания.get("Т3", {}).get("было"),
                    "note": "Октябрь 2026"
                })
            текущий_участок = участок
            текущие_показания = {}
            continue

        тариф = строка[10] if len(строка) > 10 else None
        if тариф and текущий_участок:
            тариф_стр = str(тариф).strip().upper()
            if тариф_стр in ("Т1", "Т2", "Т3", "T1", "T2", "T3"):
                было = строка[11] if len(строка) > 11 else None
                стало = строка[12] if len(строка) > 12 else None
                текущие_показания[тариф_стр] = {"было": было, "стало": стало}

    if текущий_участок and текущие_показания:
        записи.append({
            "lot": текущий_участок,
            "date": ДАТА_ПОКАЗАНИЙ,
            "t1_cur": текущие_показания.get("Т1", {}).get("стало"),
            "t1_prev": текущие_показания.get("Т1", {}).get("было"),
            "t2_cur": текущие_показания.get("Т2", {}).get("стало"),
            "t2_prev": текущие_показания.get("Т2", {}).get("было"),
            "t3_cur": текущие_показания.get("Т3", {}).get("стало"),
            "t3_prev": текущие_показания.get("Т3", {}).get("было"),
            "note": "Октябрь 2026"
        })

    wb.close()
    return записи


def защита_от_перезаписи(новые_данные):
    if not новые_данные:
        if os.path.exists(ВЫХОДНОЙ_ФАЙЛ):
            try:
                with open(ВЫХОДНОЙ_ФАЙЛ, "r", encoding="utf-8") as f:
                    старые = json.load(f)
                if старые:
                    print("ℹ️ Новые данные пусты. Старый файл сохранён без изменений.")
                    return False
            except (json.JSONDecodeError, OSError):
                pass
    return True


def сформировать_файл():
    print(f"📖 Читаем файл: {ИСХОДНЫЙ_ФАЙЛ}")

    if not os.path.exists(ИСХОДНЫЙ_ФАЙЛ):
        print(f"❌ Файл не найден: {ИСХОДНЫЙ_ФАЙЛ}")
        return

    записи = прочитать_excel(ИСХОДНЫЙ_ФАЙЛ)
    print(f"📊 Найдено записей: {len(записи)}")

    if not защита_от_перезаписи(записи):
        return

    with open(ВЫХОДНОЙ_ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(записи, f, ensure_ascii=False, indent=2)
    
    print(f"✅ Файл сохранён: {ВЫХОДНОЙ_ФАЙЛ}")


if __name__ == "__main__":
    сформировать_файл()